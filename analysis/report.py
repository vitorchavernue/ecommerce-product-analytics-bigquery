"""Write the findings report (Markdown) from the tables built by dbt.

It reads the reporting tables, runs the statistical comparisons and writes the business findings,
with every number taken from the data. The same script works on the local DuckDB file (CI) and on
BigQuery (real data).

Usage
-----
    python -m analysis.report --target local    --out data/findings_local.md
    python -m analysis.report --target bigquery --out docs/findings.md      # needs GCP_PROJECT_ID
"""

from __future__ import annotations

import argparse
import os
from datetime import date
from pathlib import Path

import pandas as pd

from analysis.stats import relative_lift, two_proportion_test, wilson_interval

HOLIDAY_START, HOLIDAY_END = date(2020, 11, 27), date(2020, 12, 14)  # Black Friday to the last shipping weeks


# --------------------------------------------------------------------------------------------
# 1. Connection: the same questions are asked to DuckDB (local) or BigQuery (production)
# --------------------------------------------------------------------------------------------
class Warehouse:
    def __init__(self, target: str, duckdb_path: str | None = None, project: str | None = None):
        self.target = target
        if target == "bigquery":
            from google.cloud import bigquery

            self.project = project or os.environ["GCP_PROJECT_ID"]
            self.client = bigquery.Client(project=self.project)
        else:
            import duckdb

            self.client = duckdb.connect(duckdb_path or "data/warehouse.duckdb", read_only=True)

    def table(self, dataset: str, name: str) -> str:
        return f"`{self.project}.{dataset}.{name}`" if self.target == "bigquery" else f"{dataset}.{name}"

    def query(self, sql: str) -> pd.DataFrame:
        if self.target == "bigquery":
            return self.client.query(sql).to_dataframe()
        return self.client.sql(sql).df()


# --------------------------------------------------------------------------------------------
# 2. Small formatting helpers for the report
# --------------------------------------------------------------------------------------------
def pct(x: float, digits: int = 2) -> str:
    return "n/a" if pd.isna(x) else f"{x * 100:.{digits}f}%"


def usd(x: float) -> str:
    return f"${x:,.0f}" if abs(x) >= 100 else f"${x:,.2f}"


def num(x: float) -> str:
    return f"{x:,.0f}"


def pval(p: float) -> str:
    return "p < 1e-16" if p < 1e-16 else f"p = {p:.1e}"


def md_table(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


# --------------------------------------------------------------------------------------------
# 3. The analysis, section by section
# --------------------------------------------------------------------------------------------
def build_report(wh: Warehouse) -> str:
    rpt = lambda name: wh.table("ga4_reporting", name)  # noqa: E731
    core = lambda name: wh.table("ga4_core", name)  # noqa: E731
    stg = lambda name: wh.table("ga4_staging", name)  # noqa: E731
    out: list[str] = ["# Findings — Google Merchandise Store (GA4, Nov 2020 – Jan 2021)", ""]
    out.append(f"_Generated by `analysis/report.py` from the dbt tables ({wh.target})._")

    # 3.1 Store overview
    k = wh.query(f"""
        select sum(sessions) sessions, sum(engaged_sessions) engaged, sum(purchase_sessions) purchase_sessions,
               sum(orders) orders, sum(revenue_usd) revenue
        from {rpt('rpt_daily_kpis')}""").iloc[0]
    users = wh.query(f"""
        select count(*) users, sum(case when is_customer then 1 else 0 end) customers
        from {core('dim_users')}""").iloc[0]
    conv = k.purchase_sessions / k.sessions
    out += ["", "## 1. Store overview", "", md_table(pd.DataFrame([{
        "Users": num(users.users), "Sessions": num(k.sessions), "Engaged sessions": pct(k.engaged / k.sessions, 1),
        "Orders": num(k.orders), "Revenue": usd(k.revenue), "Conversion (sessions)": pct(conv),
        "Average order value": usd(k.revenue / k.orders), "Revenue per session": usd(k.revenue / k.sessions),
        "Customers": num(users.customers)}]))]

    # 3.2 Purchase funnel: where visitors give up
    f = wh.query(f"select step_order, step_name, sum(sessions) sessions from {rpt('rpt_funnel')} group by 1, 2 order by 1")
    f["from_previous"] = f.sessions / f.sessions.shift(1)
    f["drop_off"] = 1 - f.from_previous
    worst = f.iloc[1:].sort_values("drop_off", ascending=False).iloc[0]
    product_viewers = f.sessions.iloc[0]
    out += ["", "## 2. Purchase funnel (closed)", "",
            md_table(pd.DataFrame({"Step": f.step_name, "Sessions": f.sessions.map(num),
                                   "Kept from previous step": f.from_previous.map(lambda x: "—" if pd.isna(x) else pct(x, 1)),
                                   "Of product viewers": (f.sessions / product_viewers).map(lambda x: pct(x, 1))})),
            "", f"- Only **{pct(f.sessions.iloc[0] / k.sessions, 1)}** of the sessions view a product page.",
            f"- The largest loss is at **{worst.step_name}**: {pct(worst.drop_off, 1)} of the sessions that reached the "
            f"previous step stop there.",
            f"- Of the sessions that view a product, **{pct(f.sessions.iloc[-1] / product_viewers, 1)}** end in a purchase."]

    # 3.3 Device and visitor type: are the gaps real?
    seg = wh.query(f"select * from {rpt('rpt_segment_conversion')}")
    dev = seg[seg.dimension == "device_category"].set_index("segment")
    lines = ["", "## 3. Device and visitor type", ""]
    if {"desktop", "mobile"} <= set(dev.index):
        t = two_proportion_test(int(dev.loc["desktop", "converted_sessions"]), int(dev.loc["desktop", "sessions"]),
                                int(dev.loc["mobile", "converted_sessions"]), int(dev.loc["mobile", "sessions"]))
        lines.append(f"- **Desktop converts {pct(t.rate_a)} vs {pct(t.rate_b)} on mobile** "
                     f"({relative_lift(t.rate_b, t.rate_a):+.0f}% on mobile; z = {t.z:.1f}, {pval(t.p_value)}"
                     f"{', significant' if t.significant else ', not significant'}).")
    vis = seg[seg.dimension == "visitor_type"].set_index("segment")
    if {"New", "Returning"} <= set(vis.index):
        t = two_proportion_test(int(vis.loc["Returning", "converted_sessions"]), int(vis.loc["Returning", "sessions"]),
                                int(vis.loc["New", "converted_sessions"]), int(vis.loc["New", "sessions"]))
        lines.append(f"- **Returning visitors convert {pct(t.rate_a)} vs {pct(t.rate_b)} for new visitors** "
                     f"({relative_lift(t.rate_a, t.rate_b):+.0f}%; {pval(t.p_value)}).")
    out += lines

    # 3.4 Channels, with confidence interval and test against the rest of the store
    ch = seg[seg.dimension == "channel"].sort_values("sessions", ascending=False)
    out += ["", "## 4. Marketing channels", "", md_table(pd.DataFrame({
        "Channel": ch.segment, "Sessions": ch.sessions.map(num), "Conversion": ch.conversion_rate.map(pct),
        "95% interval": [f"{pct(lo)} – {pct(hi)}" for lo, hi in zip(ch.conversion_ci_low, ch.conversion_ci_high, strict=True)],
        "Index vs store": ch.index_vs_store.map(lambda x: f"{x:.2f}"),
        "Revenue / session": ch.revenue_per_session.map(usd),
        "Different from the rest?": ch.is_significant.map(lambda s: "yes" if s else "no")})),
        "", "_'Unattributed' = visits whose source or medium is hidden in the public sample (`<Other>`, `(data deleted)`)._"]

    # 3.5 Holiday shopping weeks vs the rest of the period
    p = wh.query(f"""
        select case when date between date '{HOLIDAY_START}' and date '{HOLIDAY_END}' then 'holiday' else 'other' end period,
               sum(sessions) sessions, sum(purchase_sessions) converted, sum(revenue_usd) revenue, count(distinct date) n_days
        from {rpt('rpt_daily_kpis')} group by 1""").set_index("period")
    if {"holiday", "other"} <= set(p.index):
        t = two_proportion_test(int(p.loc["holiday", "converted"]), int(p.loc["holiday", "sessions"]),
                                int(p.loc["other", "converted"]), int(p.loc["other", "sessions"]))
        rev_day = p.revenue / p.n_days
        out += ["", "## 5. Holiday shopping weeks", "",
                f"- From Black Friday to mid-December ({HOLIDAY_START:%d %b} – {HOLIDAY_END:%d %b}) the store sold "
                f"**{usd(rev_day['holiday'])} per day vs {usd(rev_day['other'])}** in the rest of the period "
                f"({relative_lift(rev_day['holiday'], rev_day['other']):+.0f}%).",
                f"- Conversion: {pct(t.rate_a)} vs {pct(t.rate_b)} ({pval(t.p_value)}, "
                f"{'significant' if t.significant else 'not significant'})."]

    # 3.6 Retention of new users
    r = wh.query(f"""
        select week_number, sum(active_users) active, sum(cohort_users) cohort
        from {rpt('rpt_cohort_retention')} where is_complete_week and week_number in (1, 2, 4, 8)
        group by 1 order by 1""")
    out += ["", "## 6. Retention of new users (weekly cohorts)", "",
            md_table(pd.DataFrame({"Week after first visit": r.week_number,
                                   "Users returning": (r.active / r.cohort).map(lambda x: pct(x, 1))})),
            "", "_Weighted average of all cohorts, complete weeks only._"]

    # 3.7 Customer segments (RFM)
    s = wh.query(f"select * from {rpt('rpt_rfm_segments')} order by revenue_usd desc")
    out += ["", "## 7. Customer segments (RFM)", "", md_table(pd.DataFrame({
        "Segment": s.rfm_segment, "Customers": s.customers.map(num),
        "Share of customers": s.customer_share.map(lambda x: pct(x, 1)),
        "Share of revenue": s.revenue_share.map(lambda x: pct(x, 1)), "Avg orders": s.avg_orders.map(lambda x: f"{x:.2f}"),
        "Avg revenue": s.avg_revenue_usd.map(usd), "Avg days since last order": s.avg_recency_days.map(lambda x: f"{x:.0f}")}))]

    # 3.8 Products
    pr = wh.query(f"select * from {rpt('rpt_product_performance')} where view_sessions >= 50 order by revenue_usd desc")
    top = pr.head(10)
    out += ["", "## 8. Products", "", "Top 10 by revenue (products with at least 50 viewing sessions):", "",
            md_table(pd.DataFrame({
                "Product": top.item_name, "Category": top.item_category, "Viewing sessions": top.view_sessions.map(num),
                "Cart rate": top.cart_rate.map(lambda x: pct(x, 1)), "Units": top.units_sold.map(num),
                "Revenue": top.revenue_usd.map(usd)}))]
    if len(pr) >= 10:
        weak = pr[pr.view_sessions >= pr.view_sessions.quantile(0.75)].sort_values("cart_rate").head(5)
        out += ["", "Most viewed products with the **lowest cart rate** (review price, photos or description):", "",
                md_table(pd.DataFrame({"Product": weak.item_name, "Viewing sessions": weak.view_sessions.map(num),
                                       "Cart rate": weak.cart_rate.map(lambda x: pct(x, 1))}))]

    # 3.9 Data quality: what was cleaned before the numbers above
    q = wh.query(f"""
        select count(*) events,
               sum(case when session_key is null then 1 else 0 end) events_without_session,
               sum(case when event_name = 'purchase' then 1 else 0 end) purchase_events,
               sum(case when event_name = 'purchase' and transaction_id is null then 1 else 0 end) purchases_without_id,
               count(distinct case when event_name = 'purchase' then transaction_id end) distinct_orders
        from {stg('stg_ga4__events')}""").iloc[0]
    out += ["", "## 9. Data quality", "", md_table(pd.DataFrame([{
        "Events": num(q.events), "Events without session id": num(q.events_without_session),
        "Purchase events": num(q.purchase_events), "Purchases without transaction id (excluded)": num(q.purchases_without_id),
        "Duplicated purchase events removed": num(q.purchase_events - q.purchases_without_id - q.distinct_orders),
        "Orders": num(q.distinct_orders)}]))]

    lo, hi = wilson_interval(int(k.purchase_sessions), int(k.sessions))
    out += ["", f"_Store conversion {pct(conv)} (95% interval {pct(lo)} – {pct(hi)})._", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--target", choices=["local", "bigquery"], default="local")
    parser.add_argument("--duckdb-path", default=os.environ.get("DUCKDB_PATH", "data/warehouse.duckdb"))
    parser.add_argument("--out", type=Path, default=Path("data/findings_local.md"))
    args = parser.parse_args()
    report = build_report(Warehouse(args.target, duckdb_path=args.duckdb_path))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")
    print(f"report written to {args.out}")


if __name__ == "__main__":
    main()
